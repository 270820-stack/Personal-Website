const loader = document.querySelector("[data-loader]");
const loaderCount = document.querySelector("[data-loader-count]");
const overlay = document.querySelector("[data-overlay]");
const overlayImage = document.querySelector("[data-overlay-image]");
const overlayEmpty = document.querySelector("[data-overlay-empty]");
const overlayKicker = document.querySelector("[data-overlay-kicker]");
const overlayTitle = document.querySelector("[data-overlay-title]");
const overlayBody = document.querySelector("[data-overlay-body]");
const overlayRole = document.querySelector("[data-overlay-role]");
const overlayThumbs = document.querySelector("[data-overlay-thumbs]");
const overlayLink = document.querySelector("[data-overlay-link]");
const cursor = document.querySelector(".cursor");
const clock = document.querySelector("[data-clock]");

let lenis;

function startLoader() {
  const start = performance.now();
  const duration = 1600;

  const tick = (now) => {
    const progress = Math.min(100, Math.round(((now - start) / duration) * 100));
    loaderCount.textContent = String(progress);
    if (progress < 100) {
      requestAnimationFrame(tick);
      return;
    }
    loader.classList.add("is-done");
    document.body.classList.add("is-ready");
    startLenis();
  };

  requestAnimationFrame(tick);
}

function startLenis() {
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
  if (typeof Lenis !== "function") return;

  lenis = new Lenis({
    duration: 1.15,
    easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
  });

  const raf = (time) => {
    lenis.raf(time);
    requestAnimationFrame(raf);
  };
  requestAnimationFrame(raf);
}

function updateClock() {
  const now = new Date();
  const hk = new Intl.DateTimeFormat("en-GB", {
    timeZone: "Asia/Hong_Kong",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false,
  }).format(now);
  clock.textContent = `HK — ${hk}`;
}

function moveCursor(event) {
  cursor.style.transform = `translate3d(${event.clientX - 7}px, ${event.clientY - 7}px, 0)`;
}

function setHoverState(on) {
  document.body.classList.toggle("is-hovering", on);
}

let currentImages = [];
let currentIndex = 0;

function showImage(index) {
  if (!currentImages.length) return;
  currentIndex = (index + currentImages.length) % currentImages.length;
  const [src, alt] = currentImages[currentIndex];
  overlayImage.src = src;
  overlayImage.alt = alt;
  overlayThumbs.querySelectorAll("button").forEach((thumb, i) => {
    thumb.classList.toggle("is-active", i === currentIndex);
  });
}

function openWork(id) {
  const work = works[id];
  if (!work) return;

  currentImages = work.images || [];
  overlayThumbs.replaceChildren(
    ...(currentImages.length > 1 ? currentImages : []).map(([src, alt], i) => {
      const thumb = document.createElement("button");
      thumb.type = "button";
      thumb.setAttribute("aria-label", alt);
      const img = document.createElement("img");
      img.src = src.replace(/\/([^/]+)$/, "/t/$1");
      img.alt = "";
      thumb.append(img);
      thumb.addEventListener("click", () => showImage(i));
      return thumb;
    })
  );

  if (currentImages.length) {
    overlayImage.hidden = false;
    overlayEmpty.hidden = true;
    showImage(0);
  } else {
    overlayImage.removeAttribute("src");
    overlayImage.alt = "";
    overlayImage.hidden = true;
    overlayEmpty.hidden = false;
  }
  overlayKicker.textContent = work.kicker;
  overlayTitle.textContent = work.title;
  overlayBody.textContent = work.body;
  overlayRole.textContent = work.role || "";
  overlayLink.hidden = !work.link;
  if (work.link) overlayLink.href = work.link;
  overlay.scrollTop = 0;
  overlay.hidden = false;
  document.body.classList.add("is-overlay");
  document.body.style.overflow = "hidden";
  lenis?.stop();
}

function closeWork() {
  overlay.hidden = true;
  document.body.classList.remove("is-overlay");
  document.body.style.overflow = "";
  lenis?.start();
}

document.querySelectorAll("[data-open]").forEach((node) => {
  node.addEventListener("click", () => openWork(node.dataset.open));
});

document.querySelector("[data-close]").addEventListener("click", closeWork);

overlay.addEventListener("click", (event) => {
  if (event.target === overlay) closeWork();
});

document.addEventListener("keydown", (event) => {
  if (overlay.hidden) return;
  if (event.key === "Escape") closeWork();
  if (event.key === "ArrowRight") showImage(currentIndex + 1);
  if (event.key === "ArrowLeft") showImage(currentIndex - 1);
});

document.querySelectorAll("a, button").forEach((node) => {
  node.addEventListener("mouseenter", () => setHoverState(true));
  node.addEventListener("mouseleave", () => setHoverState(false));
});

document.querySelectorAll('a[href^="#"]').forEach((link) => {
  link.addEventListener("click", (event) => {
    const id = link.getAttribute("href");
    const target = id && document.querySelector(id);
    if (!target) return;
    event.preventDefault();
    if (lenis) {
      lenis.scrollTo(target, { offset: 0 });
    } else {
      target.scrollIntoView({ behavior: "smooth" });
    }
  });
});

window.addEventListener("pointermove", moveCursor);
updateClock();
setInterval(updateClock, 1000);
startLoader();
